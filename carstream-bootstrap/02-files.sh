cat > 'CarStream/app/src/main/assets/app.js' <<'__CARSTREAM_2_5__'
(() => {
  "use strict";

  const qs = new URLSearchParams(location.search);
  const suppliedToken = qs.get("token");
  if (suppliedToken) localStorage.setItem("carstreamToken", suppliedToken);
  const token = suppliedToken || localStorage.getItem("carstreamToken") || "";
  const generatedId = (crypto.randomUUID ? crypto.randomUUID() :
    `tablet-${Date.now()}-${Math.random().toString(16).slice(2)}`);
  const clientId = localStorage.getItem("carstreamClientId") || generatedId;
  localStorage.setItem("carstreamClientId", clientId);

  const el = id => document.getElementById(id);
  const video = el("video");
  const onboarding = el("onboarding");
  const playerPanel = el("playerPanel");
  const libraryPanel = el("libraryPanel");
  const lockedBanner = el("lockedBanner");
  const gestureButton = el("gestureButton");
  let clientName = localStorage.getItem("carstreamClientName") || "";
  let socket = null;
  let reconnectTimer = null;
  let currentMedia = null;
  let library = [];
  let controlMode = "SHARED";
  let buffering = false;
  let needsGesture = false;

  function initialize() {
    if (!token) {
      onboarding.classList.remove("hidden");
      el("nameInput").value = clientName;
      el("startButton").disabled = true;
      el("startButton").textContent = "Open the address shown on the phone";
      return;
    }
    el("clientName").textContent = clientName ? `• ${clientName}` : "";
    if (clientName) {
      showApp();
      connectSocket();
      loadLibrary();
    } else {
      onboarding.classList.remove("hidden");
      el("nameInput").focus();
    }
  }

  function showApp() {
    onboarding.classList.add("hidden");
    playerPanel.classList.remove("hidden");
    libraryPanel.classList.remove("hidden");
    el("clientName").textContent = `• ${clientName}`;
  }

  el("startButton").addEventListener("click", async () => {
    const value = el("nameInput").value.trim();
    if (!value) return;
    clientName = value;
    localStorage.setItem("carstreamClientName", clientName);
    showApp();
    connectSocket();
    loadLibrary();
    try {
      video.muted = true;
      await video.play();
      video.pause();
      video.muted = false;
    } catch (_) { }
  });

  el("renameButton").addEventListener("click", () => {
    const next = prompt("Tablet name", clientName);
    if (!next || !next.trim()) return;
    clientName = next.trim();
    localStorage.setItem("carstreamClientName", clientName);
    el("clientName").textContent = `• ${clientName}`;
    send({ type: "rename", name: clientName });
  });

  el("search").addEventListener("input", renderLibrary);
  el("playButton").addEventListener("click", () => video.paused ? attemptPlay() : video.pause());
  document.querySelector('[data-command="back"]').addEventListener("click", () => seekRelative(-10));
  document.querySelector('[data-command="forward"]').addEventListener("click", () => seekRelative(30));
  el("fullscreenButton").addEventListener("click", () => {
    const target = video.parentElement;
    if (target.requestFullscreen) target.requestFullscreen();
  });
  gestureButton.addEventListener("click", attemptPlay);

  function connectSocket() {
    clearTimeout(reconnectTimer);
    if (socket && (socket.readyState === WebSocket.OPEN || socket.readyState === WebSocket.CONNECTING)) return;
    const scheme = location.protocol === "https:" ? "wss" : "ws";
    socket = new WebSocket(`${scheme}://${location.host}/ws?token=${encodeURIComponent(token)}`);
    socket.addEventListener("open", () => {
      setConnection(true);
      send({ type: "hello", clientId, name: clientName, userAgent: navigator.userAgent });
      sendTelemetry();
    });
    socket.addEventListener("message", event => {
      try { handleMessage(JSON.parse(event.data)); } catch (_) { }
    });
    socket.addEventListener("close", () => {
      setConnection(false);
      reconnectTimer = setTimeout(connectSocket, 1500);
    });
    socket.addEventListener("error", () => socket.close());
  }

  function setConnection(online) {
    el("connection").textContent = online ? "online" : "offline";
    el("connection").className = `status ${online ? "online" : "offline"}`;
  }

  function send(message) {
    if (socket && socket.readyState === WebSocket.OPEN) socket.send(JSON.stringify(message));
  }

  async function loadLibrary() {
    el("libraryMessage").textContent = "Loading library...";
    try {
      const response = await fetch(`/api/library?token=${encodeURIComponent(token)}`, { cache: "no-store" });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const result = await response.json();
      library = result.items || [];
      el("libraryMessage").textContent = library.length ? "" :
        (result.configured ? "No playable, download-ready videos were found." : "TorBox is not configured on the phone.");
      renderLibrary();
    } catch (error) {
      el("libraryMessage").textContent = `Could not load library: ${error.message}`;
    }
  }

  function renderLibrary() {
    const container = el("library");
    container.replaceChildren();
    const needle = el("search").value.trim().toLowerCase();
    const items = library.filter(item => !needle || item.title.toLowerCase().includes(needle)
      || (item.path || "").toLowerCase().includes(needle));
    for (const item of items) {
      const button = document.createElement("button");
      button.className = "media-card";
      button.disabled = controlMode === "PARENT_LOCKED" || !item.ready;
      const title = document.createElement("strong");
      title.className = "media-title";
      title.textContent = item.title;
      const meta = document.createElement("span");
      meta.className = "media-meta";
      meta.textContent = item.ready ? formatBytes(item.size) : "Preparing in TorBox";
      button.append(title, meta);
      button.addEventListener("click", () => setMedia(item, 0, true));
      container.appendChild(button);
    }
  }

  function handleMessage(message) {
    if (message.type === "welcome") {
      applyControlMode(message.controlMode || "SHARED");
      return;
    }
    if (message.type !== "command") return;
    switch (message.action) {
      case "play": attemptPlay(); break;
      case "pause": video.pause(); break;
      case "seekRelative": seekRelative(Number(message.seconds) || 0); break;
      case "seekTo": video.currentTime = clamp(Number(message.seconds) || 0, 0, video.duration || Infinity); break;
      case "setMedia": setMedia(message.media, Number(message.startAt) || 0, message.autoplay !== false); break;
      case "controlMode": applyControlMode(message.mode || "SHARED"); break;
    }
  }

  function setMedia(item, startAt, autoplay) {
    currentMedia = item;
    needsGesture = false;
    gestureButton.classList.add("hidden");
    el("nowTitle").textContent = item.title || "Untitled video";
    video.src = `/stream/${encodeURIComponent(item.id)}?token=${encodeURIComponent(token)}`;
    video.load();
    const seekWhenReady = () => {
      if (startAt > 0 && Number.isFinite(video.duration)) video.currentTime = Math.min(startAt, video.duration);
      if (autoplay) attemptPlay();
      video.removeEventListener("loadedmetadata", seekWhenReady);
    };
    video.addEventListener("loadedmetadata", seekWhenReady);
    sendTelemetry();
  }

  async function attemptPlay() {
    try {
      await video.play();
      needsGesture = false;
      gestureButton.classList.add("hidden");
    } catch (_) {
      needsGesture = true;
      gestureButton.classList.remove("hidden");
      sendTelemetry();
    }
  }

  function seekRelative(seconds) {
    if (!Number.isFinite(video.currentTime)) return;
    video.currentTime = clamp(video.currentTime + seconds, 0, video.duration || Infinity);
  }

  function applyControlMode(mode) {
    controlMode = mode;
    const locked = mode === "PARENT_LOCKED";
    lockedBanner.classList.toggle("hidden", !locked);
    el("customControls").classList.toggle("hidden", locked);
    el("search").disabled = locked;
    video.controls = !locked;
    renderLibrary();
    sendTelemetry();
  }

  function sendTelemetry() {
    send({
      type: "telemetry",
      mediaId: currentMedia ? currentMedia.id : "",
      title: currentMedia ? currentMedia.title : "Nothing playing",
      position: Number.isFinite(video.currentTime) ? video.currentTime : 0,
      duration: Number.isFinite(video.duration) ? video.duration : 0,
      paused: video.paused,
      buffering,
      needsGesture,
      controlMode
    });
    updatePlayerText();
  }

  function updatePlayerText() {
    el("playButton").textContent = video.paused ? "Play" : "Pause";
    el("timeText").textContent = `${formatTime(video.currentTime)} / ${formatTime(video.duration)}`;
  }

  video.addEventListener("waiting", () => { buffering = true; sendTelemetry(); });
  video.addEventListener("playing", () => { buffering = false; needsGesture = false; gestureButton.classList.add("hidden"); sendTelemetry(); });
  video.addEventListener("pause", sendTelemetry);
  video.addEventListener("ended", sendTelemetry);
  video.addEventListener("timeupdate", updatePlayerText);
  setInterval(sendTelemetry, 1000);
  setInterval(loadLibrary, 30000);

  function formatTime(value) {
    if (!Number.isFinite(value) || value < 0) value = 0;
    const total = Math.floor(value);
    const h = Math.floor(total / 3600);
    const m = Math.floor((total % 3600) / 60);
    const s = total % 60;
    return h ? `${h}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}` : `${m}:${String(s).padStart(2, "0")}`;
  }

  function formatBytes(value) {
    const n = Number(value) || 0;
    if (!n) return "Video";
    if (n >= 1073741824) return `${(n / 1073741824).toFixed(1)} GB`;
    return `${Math.round(n / 1048576)} MB`;
  }

  function clamp(value, min, max) { return Math.max(min, Math.min(max, value)); }

  initialize();
})();
