# CarStream MVP

CarStream turns an Android phone into a private in-car media server. The phone creates a Wi-Fi Direct group, serves a browser client to one or more tablets, and proxies download-ready TorBox video over the phone's cellular connection.

This branch is an MVP intended for testing on real Android hardware. Use it only with media you are authorized to access.

## Included features

- One Android app on the phone. Nothing is installed on the tablets.
- Wi-Fi Direct group creation from the phone app.
- Network name, password, and tablet URL shown in the phone UI.
- Multiple tablet clients at the same time.
- Independent video streams and playback state for each client.
- Live phone dashboard showing title, elapsed time, duration, play or pause state, and buffering state.
- Per-tablet play, pause, rewind 10 seconds, fast-forward 30 seconds, and choose-media controls.
- Parent can launch a selected movie or episode on a selected tablet.
- Three control modes:
  - Shared: child and parent may both control playback.
  - Parent locked: browser controls and library selection are disabled on the tablet.
  - Observe only: the phone displays state but its remote-control buttons are disabled.
- TorBox library browsing.
- Paste a magnet link on the phone to add it to TorBox.
- HTTP byte-range proxying so each tablet can seek without downloading from the beginning.
- TorBox API key encrypted with Android Keystore.
- TorBox API key and temporary download links never sent to the tablet.
- Foreground service, wake lock, and high-performance Wi-Fi lock while serving.

## Build

Open the `CarStream` directory in Android Studio and build the `app` module. The project targets Android API 35 and has a minimum Android version of 10, API 29.

The GitHub Actions workflow on the `carstream-mvp` branch runs unit tests and creates a debug APK artifact.

## First use

1. Install the debug APK on the phone.
2. Open CarStream and grant the nearby Wi-Fi permission. Android 12L and earlier request location permission because that is how those Android versions gate Wi-Fi Direct discovery and group management.
3. Enter and save the TorBox API key.
4. Tap **Start CarStream**.
5. On each tablet, join the Wi-Fi network displayed by the phone.
6. Open the displayed local address in Chrome.
7. Give each tablet a name.

## Important MVP limitations

- Direct browser playback is most reliable with MP4 files containing H.264 video and AAC audio. Chrome may not play MKV, some HEVC files, DTS audio, or other uncommon combinations. The server does not transcode in this version.
- A browser may require one physical tap before it allows a parent-initiated video to begin with sound. CarStream reports that condition to the phone and shows a large tap prompt on the tablet.
- Wi-Fi Direct behavior varies by phone manufacturer. The app first attempts a named nonpersistent group, then falls back to credentials generated by the phone.
- The MVP reads TorBox torrent items. Usenet and WebDL libraries are not yet included.
- Local phone files, subtitles, episode metadata, artwork, queues, and autoplay-next are not yet included.
- The phone uses a local HTTP server protected by a per-run access token and the Wi-Fi group's WPA passphrase. Traffic inside that private group is not separately encrypted with HTTPS.

## Architecture

```text
TorBox CDN
    |
    | cellular network selected per upstream connection
    v
Android phone
    |  TorBox API client and range proxy
    |  Wi-Fi Direct group owner
    |  HTTP server and WebSocket controller
    v
Tablet browsers
    |  independent HTML5 video players
    |  telemetry every second
    |  remote commands over WebSocket
```

Each tablet owns its player state. The phone's `ClientRegistry` maintains a separate WebSocket for each tablet and sends targeted commands. A video request occupies its own worker, so one client seeking or buffering does not alter another client's stream.
